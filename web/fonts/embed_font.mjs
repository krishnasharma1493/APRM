// embed_font.mjs: writes web/css/fonts.css with Inter Tight embedded as a base64 data URI.
//
// Idea: a page opened from file:// with the network off cannot download a web font, and the project
// rules forbid a Google Fonts link. So the one font file travels inside the stylesheet itself.
// Source: Google Fonts (fonts.gstatic.com/s/intertight/v9, latin subset, variable weight axis),
// font version "Version 3.004", licence SIL OFL 1.1 (web/fonts/OFL.txt). Checked 2026-11-07.
// Usage: node web/fonts/embed_font.mjs. Node standard library only. O(file size).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const FONT = join(here, 'InterTight-latin.woff2');
const OUT = join(here, '..', 'css', 'fonts.css');

/* The Latin range Google Fonts serves this file for (copied from its stylesheet). */
const LATIN = 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, ' +
  'U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';

/* The stylesheet text for the given font bytes. Exported so the tests can compare it with the committed file. */
export function fontsCss(bytes) {
  return '/* fonts.css: Inter Tight, embedded so the page needs no network (generated by web/fonts/embed_font.mjs;\n' +
    ' * do not edit by hand). Source: Google Fonts, intertight v9, latin subset, font "Version 3.004".\n' +
    ' * Licence: SIL Open Font License 1.1, see web/fonts/OFL.txt. One variable file covers weights 400 to 800. */\n' +
    '@font-face {\n' +
    '  font-family: "Inter Tight";\n' +
    '  font-style: normal;\n' +
    '  font-weight: 100 900;\n' +
    '  font-display: block;\n' +
    '  src: url(data:font/woff2;base64,' + Buffer.from(bytes).toString('base64') + ') format("woff2");\n' +
    '  unicode-range: ' + LATIN + ';\n' +
    '}\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, fontsCss(readFileSync(FONT)));
  console.log('wrote web/css/fonts.css');
}
